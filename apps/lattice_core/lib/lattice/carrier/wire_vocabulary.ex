defmodule Lattice.Carrier.WireVocabulary do
  @moduledoc """
  The closed vocabulary of atom names a carrier op may carry (plan 190, ruling D2).

  Op admission on the wire depends only on the frame bytes and this list: a name outside it
  refuses the frame, so two nodes can never disagree about a frame because one happens to hold
  an atom the other lacks. Op decoding creates atoms only for listed names, which bounds the
  atom table.

  The list covers the op kinds; the authority, inbox and tombstone body tags; every command,
  field and role name declared by a `use Lattice.Replica` module; the closed cutoff vocabulary
  of `Treehouse.CatalogCutoff` (catalog evidence round-trips through the wire); and the names
  the committed conformance frames use. `mix lattice.export_vectors` writes the same list to
  `clients/lattice-client/src/wire_vocabulary.ts`, and
  `test/lattice2/wire_vocabulary_test.exs` fails until a new declaration is listed here.

  `reasons/0` is the separate, explicit set of reasons a wire report can carry: the
  `Lattice.Log.accept/2` outcomes that `Lattice.Sync.deliver/2` puts in a report. Authority
  verdicts such as `:invalid_transfer` are op-level quarantine reasons and stay out of it.
  """

